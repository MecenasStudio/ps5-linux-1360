#!/usr/bin/env python3
"""Emit a binary as a C array and a length.

The four shellcode directories each embed a raw blob into the payload, and they do
it with this rather than xxd so that the build needs nothing beyond python3.

    python3 scripts/bin2c.py shellcode_hv.text.bin > shellcode_hv.h

The array is named after the file with every character outside [A-Za-z0-9]
replaced by an underscore, and the length symbol is that name plus "_len":
shellcode_hv.text.bin becomes shellcode_hv_text_bin and shellcode_hv_text_bin_len.
Neither is const - the userland side declares them extern without it.
"""

import re
import sys
from pathlib import Path

PER_LINE = 16


def symbols_for(path: Path) -> tuple[str, str]:
    stem = re.sub(r"[^A-Za-z0-9]", "_", path.name)
    return stem, f"{stem}_len"


def emit(path: Path, out) -> int:
    blob = path.read_bytes()
    name, length = symbols_for(path)

    out.write(f"/* {path.name}: {len(blob)} bytes, generated by scripts/bin2c.py */\n")
    out.write(f"unsigned char {name}[] = {{\n")
    for start in range(0, len(blob), PER_LINE):
        row = blob[start : start + PER_LINE]
        out.write("  " + " ".join(f"0x{byte:02x}," for byte in row) + "\n")
    out.write("};\n")
    out.write(f"unsigned int {length} = {len(blob)};\n")
    return 0


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(f"usage: {argv[0]} <binary>", file=sys.stderr)
        return 2
    return emit(Path(argv[1]), sys.stdout)


if __name__ == "__main__":
    sys.exit(main(sys.argv))
